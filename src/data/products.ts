export const mapProduct = (row: any): Product => {
  const name = row.name || "Moksha Masterpiece";
  const sku = row.sku || row.label_no || row.product_code || "";
  const labelNo = row.label_no || "";
  const daiWt = parseFloat(row.dai_wt || row.daiWeight || 0);
  const daiPcs = parseInt(row.dai_pcs || row.daiPcs || 0);
  const stonesDetailStr = typeof row.stones_in_detail === 'string'
    ? row.stones_in_detail
    : (Array.isArray(row.stones_in_detail) ? JSON.stringify(row.stones_in_detail) : '');

  // 1. Infer Category if missing or empty
  let category = row.category_name || row.category;
  if (!category || (category === "Gold" && !row.category_name && !row.category)) {
    const upperName = name.toUpperCase();
    const upperSku = sku.toUpperCase();
    const upperLabel = labelNo.toUpperCase();
    const upperStones = stonesDetailStr.toUpperCase();
    
    if (upperName.includes('POLKI') || upperSku.includes('POLKI')) {
      category = 'Polki';
    } else if (upperName.includes('KUNDAN') || upperSku.includes('KUNDAN')) {
      category = 'Kundan';
    } else if (
      upperName.startsWith('D ') || 
      upperSku.startsWith('D') || 
      upperLabel.startsWith('D') || 
      daiWt > 0 || 
      daiPcs > 0 || 
      upperStones.includes('DIAMOND')
    ) {
      category = 'Diamonds';
    } else {
      category = 'Gold';
    }
  }

  // 2. Infer Type / Sub-category if missing or default
  let type = row.type;
  if (!type || (type === "Necklace" && !row.type)) {
    const combined = `${name} ${sku} ${labelNo}`.toUpperCase();
    
    if (/(TOPS|DTPS|JUMKA|JUMKI|DJK|GJM|BALI|GBL|HANGING|GHG|EARRING|STUD|BUTTALU|DBL)/i.test(combined)) {
      type = 'Ear Rings';
    } else if (/(VADDANAM|DVD|BAJUBAND|BJB)/i.test(combined)) {
      type = 'Bajubands';
    } else if (/(RING|DRG|GRG)/i.test(combined)) {
      type = 'Rings';
    } else if (/(BANGLE|DBG|GBP|KADA|GKD|BRACELET|BRACELETE|DBR)/i.test(combined)) {
      type = 'Bangles';
    } else if (/(BLACK BEED|BLACKBEED|BLACK BEEDS|BLACKBEEDS|CHAIN|GCH|BBC|DBB)/i.test(combined)) {
      type = 'Chains';
    } else {
      type = 'Necklaces';
    }
  }

  return {
    id: row.id,
    name,
    category,
    image: row.image_url || row.image || row.thumbnail_url || (Array.isArray(row.image_urls) && row.image_urls[0]) || "https://tnvdmftovccgfrllaffq.supabase.co/storage/v1/object/public/products/logo.jpg",
    productCode: row.product_code || row.sku || row.barcode || row.label_no || `MJ-${row.id ? row.id.slice(0, 6) : Date.now().toString().slice(-6)}`,
    grossWeight: parseFloat(row.gross_weight || row.gross_wt || 0),
    goldWeight: parseFloat(row.gold_weight || row.net_wt || row.gross_wt || 0),
    purity: row.purity || "22K",
    metalColor: row.metal_color || "Yellow Gold",
    price: parseFloat(row.base_price_usd || row.cost_price || row.prc_amount || 1000),
    priceBreakup: {
      metal: parseFloat(row.metal_price_usd || (row.base_price_usd ? row.base_price_usd * 0.85 : 850)),
      vaMaking: parseFloat(row.va_making_usd || row.labour_amt || row.labour_rate || 100),
      stoneBeads: parseFloat(row.stone_beads_usd || row.dia_purchase_amt || row.stone_purchase_amt || 0),
      tax: parseFloat(row.tax_usd || 50),
    },
    rating: parseFloat(row.rating || 4.8),
    popularity: parseInt(row.popularity || 100),
    createdAt: row.created_at || new Date().toISOString(),
    // Strictly 1 verified image matching the item SKU
    galleryUrls: [],
    has360View: row.has_360_view || false,
    type,
    collection: row.collection || "Legacy",
    gender: row.gender || "Women",
    occasion: row.occasion || "Bridal",
    designTheme: row.design_theme || "Traditional",
    gemstoneType: row.gemstone_type || (daiWt > 0 ? "Diamond" : "None"),
    gemstoneWeight: parseFloat(row.gemstone_weight || row.dai_wt || row.clr_stone_wt || 0),
    stockQuantity: parseInt(row.stock_quantity || row.quantity || row.pcs || 1),
    sourcingCost: parseFloat(row.sourcing_cost || row.cost_price || 0),
    matchingProductId: row.matching_product_id || undefined,
    vendorId: row.vendor_id || undefined,
    sku: row.sku || undefined,
    barcode: row.barcode || undefined,
    huid: row.huid || undefined,
    netWeight: parseFloat(row.net_wt || 0),
    daiWeight: daiWt,
    daiPcs: daiPcs,
    clrStoneWeight: parseFloat(row.clr_stone_wt || 0),
    clrStonePcs: parseInt(row.clr_stone_pcs || 0),
    wastage: parseFloat(row.wastage || 0),
    labourRate: parseFloat(row.labour_rate || 0),
    labourAmt: parseFloat(row.labour_amt || 0),
    supplierName: row.supplier_name || undefined,
    labelNo: row.label_no || undefined,
    stonesInDetail: (function() {
      if (!row.stones_in_detail) return undefined;
      if (Array.isArray(row.stones_in_detail)) return row.stones_in_detail;
      if (typeof row.stones_in_detail === 'string') {
        try { return JSON.parse(row.stones_in_detail); } catch (e) { return []; }
      }
      return undefined;
    })(),
  };
};

const productCache: Record<string, { data: Product[]; timestamp: number }> = {};
const CACHE_TTL_MS = 5 * 60 * 1000;

export const clearProductCache = () => {
  Object.keys(productCache).forEach(key => delete productCache[key]);
};

export const fetchProductsFromSupabase = async (
  category: string = "All",
  pageOrForceRefresh?: number | boolean,
  pageSize: number = 24,
  forceRefresh = false
): Promise<Product[]> => {
  let page = 0;
  let isForceRefresh = forceRefresh;

  if (typeof pageOrForceRefresh === "boolean") {
    isForceRefresh = pageOrForceRefresh;
    page = 0;
  } else if (typeof pageOrForceRefresh === "number") {
    page = pageOrForceRefresh;
  }

  const cacheKey = page > 0 ? `${category}_p${page}_s${pageSize}` : (category || "All");
  const now = Date.now();

  if (!isForceRefresh && productCache[cacheKey] && (now - productCache[cacheKey].timestamp < CACHE_TTL_MS)) {
    return productCache[cacheKey].data;
  }

  try {
    let query = supabase.from("products").select("*");
    let itemsQuery = supabase.from("items").select("*");

    if (category && category !== "All") {
      query = query.eq("category_name", category);
      itemsQuery = itemsQuery.eq("category_name", category);
    }

    if (page > 0 && pageSize > 0) {
      const from = (page - 1) * pageSize;
      const to = from + pageSize - 1;
      query = query.range(from, to);
      itemsQuery = itemsQuery.range(from, to);
    }

    // Execute both queries in parallel to drastically improve load time
    const [prodResult, itemsResult] = await Promise.all([
      query,
      Promise.resolve(itemsQuery).catch(() => ({ data: [] }))
    ]);

    const prodData = prodResult?.data || [];
    const itemsData = itemsResult?.data || [];

    const combinedRaw = [...prodData, ...itemsData];

    if (combinedRaw.length > 0) {
      const mapped = combinedRaw
        .map(mapProduct)
        .filter(p => category === "All" || p.category?.toLowerCase() === category.toLowerCase());

      if (mapped.length > 0) {
        productCache[cacheKey] = { data: mapped, timestamp: now };
        return mapped;
      }
    }
    
    let fallback = category === "All" 
      ? PRODUCTS 
      : PRODUCTS.filter(p => p.category?.toLowerCase() === category.toLowerCase());

    if (page > 0 && pageSize > 0) {
      const from = (page - 1) * pageSize;
      fallback = fallback.slice(from, from + pageSize);
    }

    productCache[cacheKey] = { data: fallback, timestamp: now };
    return fallback;
  } catch (err) {
    if (productCache[cacheKey]) return productCache[cacheKey].data;
    let fallback = category === "All" 
      ? PRODUCTS 
      : PRODUCTS.filter(p => p.category?.toLowerCase() === category.toLowerCase());
    if (page > 0 && pageSize > 0) {
      const from = (page - 1) * pageSize;
      fallback = fallback.slice(from, from + pageSize);
    }
    return fallback;
  }
};

export const fetchProductById = async (id: string): Promise<Product | null> => {
  try {
    const { data: prodData } = await supabase.from("products").select("*").eq("id", id).single();
    if (prodData) return mapProduct(prodData);
    const { data: itemData } = await supabase.from("items").select("*").eq("id", id).single();
    if (itemData) return mapProduct(itemData);
    return PRODUCTS.find(p => p.id === id) || null;
  } catch (err) {
    return PRODUCTS.find(p => p.id === id) || null;
  }
};

